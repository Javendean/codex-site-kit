#!/usr/bin/env node
/**
 * Regenerate LEARNING-PATH.md and RULES.md from the rulebook.
 *
 * Neither file is written by hand. A course maintained alongside a linter
 * drifts away from it within a month, and then the course teaches rules the
 * tool does not run — which teaches the reader to distrust the tool. These two
 * documents are projections of rules/, and this script fails loudly if the
 * path names a rule that no longer exists.
 *
 *   node scripts/build-docs.js          write the files
 *   node scripts/build-docs.js --check  verify they are up to date, write nothing
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { STOPS, render, validate } from '../src/lib/learning-path.js';
import { rulebook, TIER_LABEL as TIERS, TIER_ORDER, GLYPH, loadSources } from '../src/lib/rulebook.js';

const RULEBOOK = rulebook().rules;

/** Every source a rule cites: the primary one, plus anything in also_in. */
const sourceNames = (rule) => [rule.source?.name, ...(rule.also_in ?? []).map((a) => a.name)].filter(Boolean);
const SOURCES = loadSources().sources;
const CONFIDENCE_NOTE = {
  DEMONSTRATED: 'The source ships code, a live comparator, production library CSS, or a counted sample.',
  ASSERTED: 'Expert opinion or practitioner prose. It may well be right. It is not evidence.',
  MEASURED: 'Measured rather than quoted — the numbers in the finding are the measurement.',
  INFERRED: 'Reasoning with no source behind it, recorded as reasoning so it is never mistaken for a citation.'
};

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const { missing, uncovered } = validate();
if (missing.length) {
  process.stderr.write(
    `The learning path names rules that are not in the rulebook:\n` +
      missing.map((m) => `  stop ${m.stop}: ${m.rule}`).join('\n') +
      `\n\nFix src/lib/learning-path.js or the rulebook. A course that teaches a rule the tool\n` +
      `does not run is worse than no course.\n`
  );
  process.exit(1);
}

/* ------------------------------------------------------------------ *
 * LEARNING-PATH.md
 * ------------------------------------------------------------------ */

function learningPathMarkdown() {
  const out = [];
  out.push('# From never having made a website, to knowing why that gradient was wrong');
  out.push('');
  out.push('*Generated from the rulebook by `npm run docs`. Do not edit this file by hand —');
  out.push('edit `src/lib/learning-path.js` or the rules themselves, and regenerate.*');
  out.push('');
  out.push(
    'Ten stops. Every claim below comes out of the rulebook the tool actually runs, and every stop names the rule ids that carry its reasoning, so this route cannot drift away from the tool. Ask Codex to run `explain_rule` on any id to read its full teaching note, its sources, and how confident the research is in it.'
  );
  out.push('');
  out.push(
    'The order is **not** the rulebook\'s order. The rulebook sorts by how fast a visitor notices a fault, which is right for a critique and wrong for a beginner. This sorts by what you need first.'
  );
  out.push('');
  out.push('| | Stop | What it is about |');
  out.push('|---:|---|---|');
  for (const s of STOPS) out.push(`| ${s.n} | [${s.title}](#${slug(s.n, s.title)}) | ${firstSentence(s.claim)} |`);
  out.push('');

  for (const s of STOPS) {
    out.push('---');
    out.push('');
    out.push(`## ${s.n}. ${s.title}`);
    out.push('');
    out.push(s.claim);
    out.push('');
    out.push('**What to do**');
    out.push('');
    for (const d of s.doing) out.push(`- ${d}`);
    out.push('');
    if (s.rules.length) {
      out.push(`**The rules that carry this** — ${s.rules.length} of them:`);
      out.push('');
      for (const id of s.rules) {
        const rule = RULEBOOK.find((r) => r.id === id);
        out.push(`### \`${id}\` ${GLYPH[rule.severity]} ${rule.title}`);
        out.push('');
        out.push(`*${TIERS[rule.tier]} · confidence ${rule.source?.confidence ?? 'unstated'}*`);
        out.push('');
        out.push(`**What it looks for.** ${rule.threshold}`);
        out.push('');
        out.push(`**Why it matters.** ${rule.why_it_matters}`);
        out.push('');
        out.push(`**The better move.** ${rule.fix}`);
        out.push('');
        if (rule.teach) {
          out.push(`**What it teaches.** ${rule.teach}`);
          out.push('');
        }
        out.push(`**Who says so.** ${sourceNames(rule).map((w) => SOURCES[w]?.full_name ?? w).join(' · ')}`);
        out.push('');
        const caveats = sourceNames(rule).map((w) => SOURCES[w]).filter((src) => src && src.caveat);
        for (const src of caveats) {
          out.push(`> ⚠ **${src.label}** — ${src.caveat}`);
          out.push('');
        }
      }
    }
  }

  out.push('---');
  out.push('');
  out.push('## After the tenth stop');
  out.push('');
  out.push(
    'There is no eleventh. The rules will change — the trap tier exists precisely because they must — but the method does not: build it, run `review_site`, read one finding properly rather than fixing forty, make the move, run it again. The reasoning sticks when you can see which single change moved the count.'
  );
  out.push('');
  out.push(
    `The rulebook holds **${RULEBOOK.length} rules** across ${TIER_ORDER.length} tiers, and every one of them is taught by a stop above${uncovered.length ? ` except ${uncovered.length}, which are variants of rules that are: ${uncovered.map((u) => `\`${u}\``).join(', ')}` : ''}.`
  );
  out.push('');
  out.push('## What a confidence tag means');
  out.push('');
  out.push('| Tag | Meaning |');
  out.push('|---|---|');
  for (const [tag, note] of Object.entries(CONFIDENCE_NOTE)) out.push(`| **${tag}** | ${note} |`);
  out.push('');
  out.push(
    'This matters more than it looks. Where the research says ASSERTED rather than DEMONSTRATED, the tool reports the finding as a **question about your page**, not as a gate it failed — and it says so in the output. A hypothesis laundered into a hard gate is exactly the failure this whole kit was built to avoid.'
  );
  out.push('');
  return out.join('\n');
}

/* ------------------------------------------------------------------ *
 * RULES.md — the index, so a finding id is always lookup-able
 * ------------------------------------------------------------------ */

function rulesMarkdown() {
  const out = [];
  out.push('# The rulebook');
  out.push('');
  out.push('*Generated from `rules/` by `npm run docs`. Do not edit by hand.*');
  out.push('');
  out.push(
    `${RULEBOOK.length} rules. Every one names its source, and the kit refuses to load a rule that does not — provenance is a startup error here, not a habit. Run \`explain_rule\` with any id for the full teaching note.`
  );
  out.push('');
  out.push('`??` seen in five seconds · `?` felt but not named · `?!` a habit worth dropping · `!?` a move whose time is passing · `!` worth keeping');
  out.push('');

  for (const tier of TIER_ORDER) {
    const rules = RULEBOOK.filter((r) => r.tier === tier);
    if (!rules.length) continue;
    out.push(`## ${TIERS[tier]}`);
    out.push('');
    out.push('| | Rule | What it looks for | Confidence | Sources |');
    out.push('|---|---|---|---|---|');
    for (const r of rules) {
      out.push(
        `| ${GLYPH[r.severity]} | \`${r.id}\`<br>${escapeCell(r.title)} | ${escapeCell(firstSentence(r.threshold))} | ${r.source?.confidence ?? 'unstated'} | ${sourceNames(r).join(', ')} |`
      );
    }
    out.push('');
  }

  out.push('## Sources');
  out.push('');
  out.push('| id | Who | What it contributes | Confidence |');
  out.push('|---|---|---|---|');
  for (const [id, s] of Object.entries(SOURCES)) {
    out.push(`| \`${id}\` | ${escapeCell(s.label)} | ${escapeCell(firstSentence(s.what))} | ${s.confidence ?? '—'} |`);
  }
  out.push('');
  return out.join('\n');
}

const firstSentence = (text) => {
  const s = String(text).replace(/\s+/g, ' ').trim();
  const stop = s.search(/\.\s|\.$/);
  return stop === -1 ? s : s.slice(0, stop + 1);
};
const escapeCell = (text) => String(text).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const slug = (n, title) => `${n}-${title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;

/* ------------------------------------------------------------------ */

const targets = [
  { file: path.join(ROOT, 'LEARNING-PATH.md'), body: `${learningPathMarkdown()}\n` },
  { file: path.join(ROOT, 'RULES.md'), body: `${rulesMarkdown()}\n` }
];

let stale = 0;
for (const t of targets) {
  const current = await readFile(t.file, 'utf8').catch(() => null);
  if (current === t.body) {
    process.stderr.write(`up to date  ${path.basename(t.file)}\n`);
    continue;
  }
  if (check) {
    stale += 1;
    process.stderr.write(`STALE       ${path.basename(t.file)} — run: npm run docs\n`);
    continue;
  }
  await writeFile(t.file, t.body, 'utf8');
  process.stderr.write(`written     ${path.basename(t.file)}  (${t.body.length} bytes)\n`);
}

// A plain-text render of the same path, so `learning_path` and the file agree.
if (!check) {
  process.stderr.write(`\nThe same route, as the learning_path tool renders it:\n\n`);
  process.stderr.write(`${render({ depth: 'route' }).slice(0, 600)}…\n`);
}

process.exit(stale > 0 ? 1 : 0);
